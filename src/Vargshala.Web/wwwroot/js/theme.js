    window.applyTheme = function (themeId) {
        var t = window.vargshalaThemes[themeId] || window.vargshalaThemes['deep-teal'];
        var root = document.documentElement;
        var isDark = root.classList.contains('dark');

        root.style.setProperty('--theme-header', t.header);
        root.style.setProperty('--theme-header-dark', t.headerDark);
        root.style.setProperty('--theme-primary', t.primary);
        root.style.setProperty('--theme-primary-hover', t.primaryHover);
        root.style.setProperty('--theme-primary-light', t.primaryLight);
        root.style.setProperty('--theme-gradient-start', t.gradientStart);
        root.style.setProperty('--theme-gradient-end', t.gradientEnd);
        root.style.setProperty('--theme-light-bg', t.lightBg);
        root.style.setProperty('--theme-accent', t.accent);

        var lightCanvas = t.lightBg || t.canvasBg || '#F0FDFA';
        var darkCanvas = t.canvasDark || '#0c1417';

        root.style.setProperty('--theme-canvas-bg', lightCanvas);
        root.style.setProperty('--theme-canvas-dark', darkCanvas);
        root.style.setProperty('--theme-current-canvas', isDark ? darkCanvas : lightCanvas);

        root.style.setProperty('--theme-card-dark', t.cardDark || '#111c21');
        root.style.setProperty('--theme-card-border-dark', t.cardBorderDark || '#1e2f37');
        root.style.setProperty('--theme-card-border-light', t.cardBorderLight || '#e2f1ef');

        root.style.setProperty('--primary', t.primary);
        root.style.setProperty('--primary-light', t.primaryLight);
        root.style.setProperty('--primary-bg', t.lightBg);

        root.setAttribute('data-theme', t.id);
        localStorage.setItem('vargshala_theme', t.id);

        window.dispatchEvent(new CustomEvent('vargshala-theme-changed', { detail: t.id }));
        return t.id;
    };

    window.getAppTheme = function () {
        return localStorage.getItem('vargshala_theme') || 'deep-teal';
    };

    window.toggleAppTheme = function () {
        var isDark = document.documentElement.classList.toggle('dark');
        localStorage.setItem('theme', isDark ? 'dark' : 'light');
        var themeId = window.getAppTheme();
        window.applyTheme(themeId);
        return isDark;
    };

    window.downloadFileFromBase64 = function (filename, contentType, base64) {
        var link = document.createElement('a');
        link.download = filename;
        link.href = 'data:' + contentType + ';base64,' + base64;
        document.body.appendChild(link);
        link.click();
        document.body.removeChild(link);
    };

    // Immediate self-execution on script load to prevent FOUC
    try {
        var dark = localStorage.getItem('theme');
        if (dark === 'dark' || (!dark && window.matchMedia('(prefers-color-scheme: dark)').matches)) {
            document.documentElement.classList.add('dark');
        } else {
            document.documentElement.classList.remove('dark');
        }
        var savedTheme = localStorage.getItem('vargshala_theme') || 'deep-teal';
        window.applyTheme(savedTheme);
    } catch (e) {
        console.error('Error applying theme:', e);
    }

    // Cross-tab synchronization
    window.addEventListener('storage', function (e) {
        if (e.key === 'vargshala_theme' && e.newValue) {
            window.applyTheme(e.newValue);
        } else if (e.key === 'theme' && e.newValue) {
            if (e.newValue === 'dark') {
                document.documentElement.classList.add('dark');
            } else {
                document.documentElement.classList.remove('dark');
            }
        }
    });
